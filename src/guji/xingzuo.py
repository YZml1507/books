# ---------------------------------------------------------------------------
# 太阳星座（本命星座）：由出生【月日】决定，与干支无关。
#
# R220b 修 P0：`_cross_ref_bazi` 等交叉引用曾用 `day_sign(日支)`（"今日值宫"
# 的查表键）当用户的太阳星座 —— 那是"今天哪一宫当值"，不是"你是什么座"。
# 后果：2005-06-06 生（真实双子）被告知"你的太阳星座是金牛"，且连续四天
# 出生的人得到金牛/白羊/双鱼/水瓶四个不同结果（太阳星座一个月内本应稳定）。
# 太阳星座按回归黄道的通用民用边界判定（每宫起始月日，下界含当日）。
# ---------------------------------------------------------------------------
# (起始月, 起始日, 今名) —— 该日起进入此宫，直到下一宫起始日前一天
_SUN_SIGN_BOUNDS: tuple[tuple[int, int, str], ...] = (
    (1, 20, "水瓶"), (2, 19, "双鱼"), (3, 21, "白羊"), (4, 20, "金牛"),
    (5, 21, "双子"), (6, 22, "巨蟹"), (7, 23, "狮子"), (8, 23, "处女"),
    (9, 23, "天秤"), (10, 24, "天蝎"), (11, 23, "射手"), (12, 22, "摩羯"),
)


def sun_sign(month: int, day: int) -> str:
    """出生月日 → 太阳星座今名。1/1-1/19 与 12/22 之后同属摩羯。

    纯函数：固定输入必得固定输出。越界月日返回空串。
    """
    try:
        m, d = int(month), int(day)
    except (TypeError, ValueError):
        return ""
    if not (1 <= m <= 12 and 1 <= d <= 31):
        return ""
    # 从后往前找第一个"起始日 <= 生日"的宫；都不满足 = 1 月上旬 → 摩羯
    for bm, bd, name in reversed(_SUN_SIGN_BOUNDS):
        if (m, d) >= (bm, bd):
            return name
    return "摩羯"


# ---------------------------------------------------------------------------
# R226b：每宫今日文案的**行动方向倾向**。
#
# 起因（审查轨 R222a 抓到）：`_cross_ref_tarot` / `_cross_ref_liuyao` 声称
# 输出"两个信号的关系"，但那句 relation 只是牌面正逆/动爻数的纯函数 ——
# 无论今天是白羊（劝你说出口）还是金牛（劝你放慢），逆位都输出同一句
# "和今天的节奏不完全一致"。**它从没比较过两个信号**，名不副实。
#
# 要真比较，值宫这一侧也必须有方向。这里按每宫 note 的语义归三档：
#   forward  往前走 / 表达 / 出发
#   hold     放慢 / 稳住 / 照顾自己
#   observe  观望 / 相信直觉 / 等答案浮现
# 归档依据是 SIGNS[x]["note"] 的原文，不是星座刻板印象。
# ---------------------------------------------------------------------------
SIGN_DIRECTION: dict[str, str] = {
    "白羊": "forward",   # 把心里的话说出口
    "狮子": "forward",   # 发光的日子，藏不住
    "射手": "forward",   # 想出发就出发
    "双子": "forward",   # 脑子转得快，把灵感记下来
    "处女": "forward",   # 细节控的胜利，会被看见
    "金牛": "hold",      # 节奏放慢一点也没关系
    "巨蟹": "hold",      # 先给自己倒杯水
    "摩羯": "hold",      # 默默努力，运气悄悄靠近
    "天秤": "observe",   # 抛到一半你就知道答案
    "天蝎": "observe",   # 相信第一感觉
    "双鱼": "observe",   # 梦是愿望的预告
    "水瓶": "observe",   # 特立独行是你的签名
}


def sign_direction(sign: str) -> str:
    """某宫今日文案的行动方向倾向：forward / hold / observe。未知宫返回 ''。"""
    return SIGN_DIRECTION.get(sign or "", "")


def sun_sign_profile(month: int, day: int) -> dict:
    """太阳星座 + 该宫的分维度文案（爱情/事业/财运）。未知月日返回 {}。"""
    name = sun_sign(month, day)
    if not name:
        return {}
    s = SIGNS[name]
    return {
        "sign": name,
        "palace": s["palace"],
        "star": s["star"],
        "note": s["note"],
        "love": s.get("love", ""),
        "career": s.get("career", ""),
        "wealth": s.get("wealth", ""),
    }


def citation_for(sign: str) -> dict:
    """某宫的引文锚点（判据 10 可追溯性）。sign 用今名。"""
    a = SIGNS.get(sign, {}).get("anchor")
    if not a:
        return {}
    return {"work_id": a[0], "page_anchor": a[1], "needle": a[2]}


