# 高频情绪信号词——命中时给安抚分支开头（噩梦/反复梦先看人再看象征）
_SCARE_HINTS = ("吓醒", "噩梦", "吓哭", "不敢睡", "害怕", "好可怕", "鬼压床")
_RECUR_HINTS = ("又梦到", "又梦见", "反复", "总是梦到", "总是梦见",
                "经常梦到", "经常梦见", "连续", "每次都")

_DISCLAIMER = "梦是情绪的回声，不是预言书：听着玩，别拿它做决定。"


def _norm(text: str) -> str:
    """轻归一：去标点空白，保留中文/字母数字本体。"""
    return re.sub(r"[\s，。！？、；：,.!?;:'\"（）()【】\[\]~…—\-]+", "",
                  (text or "").lower())


def interpret_dream(text: str) -> dict:
    """梦境文本 → {symbols, reply, matched}。

    symbols: [{name, trad, echo, act}] 最多 3 个，按文中出现顺序去重。
    reply:   组好的暖口语行列表（前端直接逐行渲染）。
    """
    raw = (text or "").strip()
    n = _norm(raw)
    out: dict = {"symbols": [], "reply": [], "matched": False,
                 "disclaimer": _DISCLAIMER}
    if not n:
        out["reply"] = ["跟我说说梦里最清楚的画面，一句话也行，"
                        "比如「梦见掉牙」或者「被人追了一路」。"]
        return out
    if len(raw) > 300:
        raw = raw[:300]   # 超长截断——只拿前面最鲜的画面

    seen = set()
    for sym in _DREAM_SYMS:
        if len(out["symbols"]) >= 3:
            break
        for k in sym["keys"]:
            if k and _norm(k) in n:
                if sym["name"] in seen:
                    break
                seen.add(sym["name"])
                out["symbols"].append(
                    {kk: sym[kk] for kk in ("name", "trad", "echo", "act")})
                break

    lines: list[str] = []
    scare = any(h in n for h in _SCARE_HINTS)
    recur = any(h in n for h in _RECUR_HINTS)
    if scare:
        lines.append("先抱抱你，被梦吓醒的劲儿还没散吧。"
                     "梦里的东西伤不到你，先喝口水缓一缓。")
    if recur and out["symbols"]:
        lines.append("同一个画面反复来，说明那件心事一直没消化完。"
                     "不是梦缠着你，是事还挂在那。")
    elif recur:
        lines.append("老是做同一类的梦，多半是有件事一直没翻篇。"
                     "想想最近最挂心的是哪一件。")

    syms = out["symbols"]
    if syms:
        out["matched"] = True
        if not scare and not recur:
            lines.append("这个梦我帮你翻了翻。")
        for s in syms:
            lines.append(f"「{s['name']}」，{s['trad']}。"
                         f"回声这边看：{s['echo']}。")
        # 微行动取第一命中象征的（避免一排任务清单）
        lines.append(syms[0]["act"] + "。")
        lines.append(_DISCLAIMER)
    else:
        lines.append("你这个梦不在我常用的册子里，不要紧，梦大半是"
                     "白天情绪的回声。跟我说说梦里最让你记得的那个"
                     "画面或感觉？我陪你拆。")
        lines.append(_DISCLAIMER)
    out["reply"] = lines
    return out


def facts_dream(result: dict) -> list[str]:
    """dream 卡事实 → chat/polish 注入（照 facts_xzmatch 先例）。"""
    facts: list[str] = []
    syms = (result or {}).get("symbols") or []
    for s in syms[:3]:
        facts.append("梦见「{}」：老话口径「{}」；回声读法「{}」".format(
            s.get("name"), s.get("trad"), s.get("echo")))
    acts = [s.get("act") for s in syms[:1] if s.get("act")]
    if acts:
        facts.append("建议的小动作：" + acts[0])
    facts.append("口径：梦是情绪回声不是预言，陪聊不劝行动")
    return facts
