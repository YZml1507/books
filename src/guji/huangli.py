def pengzu_baiji(dt: datetime) -> dict[str, str]:
    """dt 这天的彭祖百忌（天干 + 地支）。"""
    jd = jdn(dt.year, dt.month, dt.day)
    gz = (jd + 49) % 60
    gan = GAN[gz % 10]
    zhi = ZHI[gz % 12]
    return {"gan": gan, "zhi": zhi,
            "gan_text": PENGZU_GAN[gan], "zhi_text": PENGZU_ZHI[zhi]}


